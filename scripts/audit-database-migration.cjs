// Offline source/schema inventory. Never loads server.js, dotenv, or connects to a database.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const models = {
  ...require('../models'),
  StudentFeedback: require('../services/student-feedback').StudentFeedback,
  EventReport: require('../services/event-reports').EventReport,
  AccountPhoto: require('../services/account-photo').AccountPhoto
};
function value(v) {
  if (v === undefined) return { kind: 'absent' };
  if (typeof v === 'function') return { kind: 'function', source: String(v) };
  return v;
}
function sqlType(p) {
  if (p.schema || ['Array', 'Mixed', 'Embedded'].includes(p.instance)) return 'NVARCHAR(MAX) JSON or ordered child table; see plan';
  if (p.instance === 'ObjectId') return 'CHAR(24) COLLATE Latin1_General_100_BIN2';
  if (p.instance === 'Date') return 'DATETIME2(3) UTC';
  if (p.instance === 'Boolean') return 'BIT';
  if (p.instance === 'Number') return 'FLOAT(53); use BIGINT only after integer/range profiling';
  return p.options.maxlength ? `NVARCHAR(${p.options.maxlength})` : 'NVARCHAR(MAX); bounded index keys require live length profiling';
}
function fields(schema, prefix = '') {
  return Object.entries(schema.paths).flatMap(([name, p]) => {
    const field = {
      path: prefix + name, mongoType: p.instance, sqlProposal: sqlType(p),
      required: value(p.options.required), default: value(p.options.default),
      enum: p.enumValues?.length ? p.enumValues : p.options.enum,
      min: p.options.min, max: p.options.max, maxlength: p.options.maxlength,
      trim: p.options.trim, lowercase: p.options.lowercase, select: p.options.select,
      ref: p.options.ref, elementType: p.$embeddedSchemaType?.instance,
      validators: p.validators.map(v => ({ type: v.type, function: String(v.validator) }))
    };
    return [field, ...(p.schema ? fields(p.schema, `${prefix}${name}${p.instance === 'Array' ? '[]' : ''}.`) : [])];
  });
}
const excluded = new Set(['node_modules', '.git', '.vercel', '.frontend-audit', '.agents', '.codex']);
function walk(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    if (excluded.has(entry.name) || entry.name.startsWith('.env')) return [];
    const full = path.join(dir, entry.name);
    return entry.isDirectory() ? walk(full) : /\.(?:js|cjs|html|css)$/.test(entry.name) && !/\.min\./.test(entry.name) ? [full] : [];
  });
}
const sources = walk(root).filter(file => !file.includes(`${path.sep}docs${path.sep}database-migration${path.sep}`));
const files = sources.map(file => {
  const source = fs.readFileSync(file, 'utf8');
  const lines = source.split(/\r?\n/);
  return {
    file: path.relative(root, file).replaceAll('\\', '/'),
    sha256: crypto.createHash('sha256').update(source).digest('hex'), lines: lines.length,
    environment: [...new Set([...source.matchAll(/process\.env\.([A-Z][A-Z0-9_]*)/g)].map(m => m[1]))].sort(),
    routes: lines.flatMap((line, i) => /\b(?:app|router)\.(?:get|post|put|patch|delete|use)\(/.test(line) ? [{ line: i + 1, source: line.trim() }] : []),
    dependencies: lines.flatMap((line, i) => /mongoose|\.collection\(|\.(?:findOne|findById|findOneAndUpdate|findByIdAndUpdate|find|create|save|updateOne|updateMany|deleteOne|deleteMany|aggregate|bulkWrite|insertMany|countDocuments|exists|withTransaction|startSession|createIndexes|dropIndex|watch|populate|readConcern)\(/.test(line) ? [{ line: i + 1, source: line.trim() }] : [])
  };
});
const inventory = {
  scope: 'Offline declared schemas and source call sites; live collections, indexes, data quality, backups and SQL connectivity NOT verified. Routes are source candidates, not a runtime router manifest; inspect variable/array registrations.',
  models: Object.entries(models).map(([name, model]) => ({ name, collection: model.collection.collectionName,
    table: `dbo.${name}`, options: { timestamps: model.schema.options.timestamps, versionKey: model.schema.options.versionKey, autoIndex: model.schema.options.autoIndex },
    fields: fields(model.schema), indexes: model.schema.indexes() })), files
};
const out = path.join(root, 'docs', 'database-migration');
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'inventory.json'), JSON.stringify(inventory, null, 2) + '\n');
const rows = ['# Declared collection and field mapping', '', inventory.scope, '', 'Generated by `node scripts/audit-database-migration.cjs`. No database access.', ''];
for (const model of inventory.models) {
  rows.push(`## ${model.collection} → ${model.table}`, '', '| Source field | Declared type | Proposed SQL representation |', '| --- | --- | --- |');
  for (const f of model.fields) rows.push(`| ${f.path} | ${f.mongoType} | ${f.sqlProposal} |`);
  rows.push('', 'Declared indexes (not verified against live database):', '', '```json', JSON.stringify(model.indexes, null, 2), '```', '');
}
fs.writeFileSync(path.join(out, 'FIELD-MAPPING.md'), rows.join('\n') + '\n');
console.log(JSON.stringify({ models: inventory.models.length, fields: inventory.models.reduce((sum, m) => sum + m.fields.length, 0), sourceFiles: files.length, routeCandidates: files.reduce((sum, f) => sum + f.routes.length, 0), output: 'docs/database-migration' }));
